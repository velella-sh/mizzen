// Writes the "Data sites at scale" section of the performance docs from the benchmark's own JSON, so no number in them
// is typed by hand. The input is a report printed by `scripts/bench-data.ts` (kept in bench/last-run.json) and the
// budgets in bench/budget.json; the output is the section between the markers in docs/performance.md and the whole
// of site/performance.md.
//
// Usage: node scripts/perf-doc.ts [--report bench/last-run.json] [--budget bench/budget.json] [--check]
//   --check  writes nothing and exits 1 when either page differs from what the report generates (the test runs this).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import type { BenchReport, BudgetFile, Measurement } from "./bench-data.ts";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
export const START = "<!-- bench:start (generated by scripts/perf-doc.ts; do not edit) -->";
export const END = "<!-- bench:end -->";

const CASE_LABEL: Record<string, string> = {
  cold: "cold build, no cache",
  warm: "nothing changed",
  "one-record": "one record edited",
  search: "search index alone",
};

const seconds = (ms: number): string => `${(ms / 1000).toFixed(1)} s`;
const count = (n: number): string => n.toLocaleString("en-US");
/** A stage time: milliseconds under a second, seconds above it. */
const stageTime = (ms: number): string => (ms < 1000 ? `${Math.round(ms)} ms` : seconds(ms));

/** The generated section: machine, table of measurements next to their budgets, and the fall-back rules. */
export function section(report: BenchReport, budgets: BudgetFile): string {
  const rows: string[] = [
    "| Records | Case | Time | Budget | Peak memory | Budget | Index | Pages rendered | Pages reused |",
    "| ---: | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
  ];
  const by = (m: Measurement) => budgets.budgets[String(m.records)]?.[m.case];
  for (const m of report.measurements) {
    const b = by(m);
    rows.push(
      [
        count(m.records),
        CASE_LABEL[m.case] ?? m.case,
        seconds(m.ms),
        b === undefined ? "–" : seconds(b.ms),
        `${count(m.peakMb)} MB`,
        b === undefined ? "–" : `${count(b.peakMb)} MB`,
        m.case === "search" ? `${count(m.indexKb)} KB` : "–",
        m.case === "search" ? "–" : count(m.renderedPages),
        m.case === "search" ? "–" : count(m.cachedPages),
      ].join(" | ").replace(/^/, "| ").replace(/$/, " |"),
    );
  }
  const timed = report.measurements.flatMap((m) => (m.timings === undefined ? [] : [{ m, t: m.timings }]));
  const stageRows = timed.map(
    ({ m, t }) =>
      `| ${count(m.records)} | ${CASE_LABEL[m.case] ?? m.case} | ${stageTime(t.dataMs)} | ${stageTime(t.renderMs)} | ${stageTime(t.outputsMs)} | ${stageTime(t.writeMs)} |`,
  );
  return [
    START,
    "",
    `Measured by \`scripts/bench-data.ts\` on ${report.cpu ?? "an unrecorded CPU"} (${report.platform}/${report.arch}), Node ${report.node.replace(/^v/, "")}, ` +
      `the median of ${report.runs} run${report.runs === 1 ? "" : "s"} per row, each build in its own process so the peak memory is that build's own. ` +
      "The site is `fixtures/data-large`, generated from a fixed seed; the theme is the sibling Lateen checkout.",
    "",
    ...rows,
    "",
    ...(timed.length === 0
      ? []
      : [
          "Where each build's own time went, as the pipeline measured it: **data** is reading the site and building its model, **page generation** is the theme rendering pages, **outputs** is running them, and **write** is the output folder and the cache.",
          "",
          "| Records | Case | Data | Page generation | Outputs | Write |",
          "| ---: | --- | ---: | ---: | ---: | ---: |",
          ...stageRows,
          "",
        ]),
    "The budgets are what the `data benchmark` CI job enforces; the measurements are one machine's, and a slower runner is why a budget is about twice the number next to it. A whole-build cache hit runs no stage, so it has no row in the stage table.",
    "",
    END,
  ].join("\n");
}

/** The page for the docs site: front matter, the section, and what makes a build start over. */
export function sitePage(report: BenchReport, budgets: BudgetFile): string {
  return `---
title: Performance at scale
description: "What a data site of thousands of records costs to build, what a one-record change rebuilds, and what makes a build start over."
layout: doc
permalink: /performance/
---

A site with ten thousand records builds, and a change to one record rebuilds that record's page, not the site. This page
is generated from the benchmark's own output: \`node scripts/bench-data.ts\` prints the numbers, \`bench/budget.json\` holds the
limits CI enforces, and \`node scripts/perf-doc.ts\` writes the table below.

${section(report, budgets)}

## What one changed record rebuilds

Editing a field of one record renders that record's page again and reuses every other page's render. The pages that
list the record, and the outputs built from all of them (the sitemap, feeds, search index and the like), are produced
again from the site model, which is cheap next to rendering a page. The result is byte for byte what a clean build writes.

## What makes a build start over

A build reuses a page's render only when everything that page could show is unchanged. These make every page render
again:

- A change to the configuration, the navigation, a theme file, a layout, or the engine or Node version.
- A page or record that is added, removed, renamed, or given a new title or URL, because any page can link to it and
  show its title in the navigation.
- A change to a collection's schema, its declaration in the configuration, or a lock file it reads.
- A site with a \`mizzen.config.ts\` code file, whose plugins can read what cannot be keyed: it always builds cold.
- A cache entry that is missing, corrupt, or from another format: it is a miss, and the page is rendered.

A layout that reads another record's fields without being a list page is outside this: it cannot be keyed by the record
it renders, so keep such reads to list pages, or to the records a page references.
`;
}

/** The performance doc with its generated section replaced. */
export function withSection(doc: string, generated: string): string {
  const from = doc.indexOf(START);
  const to = doc.indexOf(END);
  if (from < 0 || to < from) throw new Error(`docs/performance.md has no generated section between ${START} and ${END}`);
  return `${doc.slice(0, from)}${generated}${doc.slice(to + END.length)}`;
}

export function generate(root: string, reportPath: string, budgetPath: string): { path: string; text: string }[] {
  const report = JSON.parse(readFileSync(reportPath, "utf8")) as BenchReport;
  const budgets = JSON.parse(readFileSync(budgetPath, "utf8")) as BudgetFile;
  const doc = readFileSync(`${root}docs/performance.md`, "utf8");
  return [
    { path: `${root}docs/performance.md`, text: withSection(doc, section(report, budgets)) },
    { path: `${root}site/performance.md`, text: sitePage(report, budgets) },
  ];
}

if (process.argv[1] && fileURLToPath(new URL(`file://${process.argv[1]}`)) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const value = (name: string, fallback: string): string => {
    const at = args.indexOf(`--${name}`);
    return at >= 0 && args[at + 1] !== undefined ? (args[at + 1] as string) : fallback;
  };
  const files = generate(ROOT, value("report", `${ROOT}bench/last-run.json`), value("budget", `${ROOT}bench/budget.json`));
  if (args.includes("--check")) {
    const stale = files.filter((file) => readFileSync(file.path, "utf8") !== file.text);
    for (const file of stale) console.error(`${file.path} is not what bench/last-run.json generates; run node scripts/perf-doc.ts`);
    if (stale.length > 0) process.exitCode = 1;
  } else {
    for (const file of files) writeFileSync(file.path, file.text);
  }
}
