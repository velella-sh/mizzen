import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";
import { parse } from "yaml";
import { readImportSource } from "../../src/import/source.ts";
import { starlightImporter } from "../../src/import/starlight/importer.ts";

/** A temporary Starlight tree with a sidebar in its integration block. */
function site(): string {
  const root = mkdtempSync(join(tmpdir(), "import-starlight-sidebar-"));
  const files: Record<string, string> = {
    "astro.config.mjs": `import starlight from "@astrojs/starlight";

export default {
  integrations: [starlight({
    title: "Sidebar site",
    sidebar: [
      { label: "Guide", items: [
        { slug: "guide/install" },
        { label: "External", link: "https://example.com/docs" },
      ] },
      { label: "Install", slug: "guide/install" },
      { label: "Auto", autogenerate: { directory: "guide" } },
    ],
  })],
  srcDir: "./src",
};
`,
    "src/content/docs/index.md": "---\ntitle: Home\n---\n\nHome.\n",
    "src/content/docs/guide/install.md": "---\ntitle: Install\n---\n\nInstall.\n",
  };
  for (const [path, text] of Object.entries(files)) {
    mkdirSync(join(root, path, ".."), { recursive: true });
    writeFileSync(join(root, path), text);
  }
  return root;
}

test("a literal Starlight sidebar becomes the generated navigation with labels, links, and autogenerated pages", async () => {
  const root = site();
  try {
    const outcome = await starlightImporter.import(readImportSource(root));
    assert.ok(outcome.navigation);
    assert.equal(outcome.navigation.source, "astro.config.mjs");
    assert.deepEqual(parse(outcome.navigation.contents), {
      main: [
        {
          title: "Guide",
          children: [
            { title: "Install", url: "/guide/install/" },
            { title: "External", url: "https://example.com/docs" },
          ],
        },
        { title: "Install", url: "/guide/install/" },
        { title: "Auto", children: [{ title: "Install", url: "/guide/install/" }] },
      ],
    });
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test("a sidebar that is not a literal list leaves navigation unset", async () => {
  const root = mkdtempSync(join(tmpdir(), "import-starlight-sidebar-"));
  try {
    mkdirSync(join(root, "src/content/docs"), { recursive: true });
    writeFileSync(join(root, "src/content/docs/index.md"), "# Home\n");
    writeFileSync(
      join(root, "astro.config.mjs"),
      'import starlight from "@astrojs/starlight";\nexport default { integrations: [starlight({ title: "T", sidebar: sidebarOf() })], srcDir: "./src" };\n',
    );
    const outcome = await starlightImporter.import(readImportSource(root));
    assert.equal(outcome.navigation, undefined);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});
