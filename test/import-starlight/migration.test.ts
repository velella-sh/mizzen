const BILINGUAL = fileURLToPath(new URL("../../fixtures/import-starlight/bilingual", import.meta.url));
const THEME = fileURLToPath(new URL("../../../lateen", import.meta.url));

/** A temporary Starlight tree holding `files`, with `srcDir: "./src"`. */
function tree(files: Record<string, string>): string {
  const root = mkdtempSync(join(tmpdir(), "import-starlight-"));
  const config = 'import starlight from "@astrojs/starlight";\nexport default { integrations: [starlight({ title: "T" })], srcDir: "./src" };\n';
  for (const [path, text] of Object.entries({ "astro.config.mjs": config, ...files })) {
    mkdirSync(dirname(join(root, path)), { recursive: true });
    writeFileSync(join(root, path), text);
  }
  return root;
}

test("an autogenerated sidebar groups folders and follows sidebar.order and sidebar.label", async () => {
  const root = tree({
    "astro.config.mjs":
      'import starlight from "@astrojs/starlight";\nexport default { integrations: [starlight({ title: "T", sidebar: [{ label: "Auto", autogenerate: { directory: "guide" } }] })], srcDir: "./src" };\n',
    "src/content/docs/index.md": "---\ntitle: Home\n---\n# Home\n",
    "src/content/docs/guide/start.md": "---\ntitle: Start\nsidebar: { order: 2 }\n---\n# Start\n",
    "src/content/docs/guide/intro.md": "---\ntitle: Intro\nsidebar: { order: 1, label: Begin }\n---\n# Intro\n",
    "src/content/docs/guide/deep/one.md": "---\ntitle: One\n---\n# One\n",
  });
  try {
    const outcome = await starlightImporter.import(readImportSource(root));
    assert.ok(outcome.navigation !== undefined);
    assert.deepEqual(parse(outcome.navigation.contents), {
      main: [
        {
          title: "Auto",
          children: [
            { title: "Begin", url: "/guide/intro/" },
            { title: "Start", url: "/guide/start/" },
            { title: "One", url: "/guide/deep/one/" },
          ],
        },
      ],
    });
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test("locales become the generated languages list and keep the translated page paths", async () => {
  const root = tree({
    "astro.config.mjs":
      'import starlight from "@astrojs/starlight";\nexport default { i18n: { defaultLocale: "en", locales: ["en", "fa"] }, integrations: [starlight({ title: "T" })], srcDir: "./src" };\n',
    "src/content/docs/index.md": "---\ntitle: Home\n---\n# Home\n",
    "src/content/docs/fa/index.md": "---\ntitle: خانه\n---\n# خانه\n",
  });
  try {
    const outcome = await starlightImporter.import(readImportSource(root));
    assert.equal(outcome.pages.find((page) => page.source.endsWith("fa/index.md"))?.destination, "fa/index.md");
    assert.match(outcome.config.contents, /code: fa/);
    assert.match(outcome.config.contents, /prefix: \/fa/);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test("public files become site-root assets, and a missing relative asset is reported", async () => {
  const root = tree({
    "src/content/docs/index.md": "---\ntitle: Home\n---\n# Home\n\n![Logo](./logo.png) ![Gone](./gone.png)\n",
    "src/content/docs/logo.png": "png",
    "public/beacon.pdf": "pdf",
  });
  try {
    const outcome = await starlightImporter.import(readImportSource(root));
    assert.deepEqual(outcome.assets, [
      { source: "src/content/docs/logo.png", destination: "logo.png" },
      { source: "public/beacon.pdf", destination: "beacon.pdf" },
    ]);
    assert.deepEqual(
      outcome.diagnostics.map((diagnostic) => [diagnostic.id, diagnostic.severity]),
      [["import.asset-missing", "warning"]],
    );
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test("a bilingual site under a base imports and builds with reachable links and assets", async () => {
  const parent = mkdtempSync(join(tmpdir(), "import-starlight-bilingual-"));
  const generated = join(parent, "project");
  const out = join(parent, "site");
  try {
    const source = readImportSource(BILINGUAL);
    const outcome = await starlightImporter.import(source);
    assert.equal(outcome.base, "/beacon");
    assert.deepEqual(outcome.diagnostics, []);

    const { files } = inventoryOf(source.files, outcome.files);
    const { mappings } = buildMappings(files, outcome.pages, outcome.assets, outcome.config, outcome.base);
    const links = rewriteLinks(outcome.pages, mappings, {
      ...(outcome.base === undefined ? {} : { base: outcome.base }),
      ...(outcome.contentRoot === undefined ? {} : { contentRoot: outcome.contentRoot }),
    });
    const written = generateProject({
      source,
      destination: generated,
      mappings,
      pages: links.pages,
      assets: outcome.assets,
      config: outcome.config,
      ...(outcome.navigation === undefined ? {} : { navigation: outcome.navigation }),
    });
    assert.deepEqual(written.diagnostics.filter((diagnostic) => diagnostic.severity === "error"), []);
    assert.match(readFileSync(join(generated, "mizzen.yml"), "utf8"), /base: "\/beacon"/);
    assert.match(readFileSync(join(generated, "_data/navigation.yml"), "utf8"), /title: Guides/);

    const result = await build({ root: generated, out, themeRoot: THEME, defaultLayout: "doc" });
    assert.deepEqual(result.diagnostics.filter((diagnostic) => diagnostic.severity === "error"), []);
    assert.deepEqual(result.diagnostics.filter((diagnostic) => diagnostic.id === "link.missing-page"), []);
    assert.match(readFileSync(join(out, "index.html"), "utf8"), /href="\/beacon\/guide\/install\/"/);
    assert.match(readFileSync(join(out, "fa/index.html"), "utf8"), /خانه/);
  } finally {
    rmSync(parent, { recursive: true, force: true });
  }
});
