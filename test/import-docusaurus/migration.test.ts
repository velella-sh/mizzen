import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";
import { generateProject } from "../../src/import/generate.ts";
import { inventoryOf } from "../../src/import/inventory.ts";
import { rewriteLinks } from "../../src/import/links.ts";
import { buildMappings } from "../../src/import/mapping.ts";
import { readImportSource } from "../../src/import/source.ts";
import { docusaurusImporter } from "../../src/import/docusaurus/index.ts";
import { build } from "../../src/pipeline/build.ts";

const THEME = fileURLToPath(new URL("../../../lateen", import.meta.url));
const CONFIG = "module.exports = { presets: [['classic', { docs: { path: 'docs' } }]] };\n";

/** A temporary Docusaurus tree holding `files`, with a classic config. */
function tree(files: Record<string, string>): string {
  const root = mkdtempSync(join(tmpdir(), "import-docusaurus-"));
  for (const [path, text] of Object.entries({ "docusaurus.config.js": CONFIG, ...files })) {
    mkdirSync(dirname(join(root, path)), { recursive: true });
    writeFileSync(join(root, path), text);
  }
  return root;
}

/** The navigation a tree converts to. */
async function navigation(root: string): Promise<unknown> {
  const outcome = await docusaurusImporter.import(readImportSource(root));
  assert.ok(outcome.navigation !== undefined);
  return parse(outcome.navigation.contents);
}

test("an autogenerated sidebar is rebuilt from folders, positions, and _category_ files", async () => {
  const root = tree({
    "sidebars.js": "module.exports = { docs: [{ type: 'autogenerated', dirName: '.' }] };\n",
    "docs/start.md": "---\ntitle: Start\nsidebar_position: 1\n---\n# Start\n",
    "docs/intro.md": "---\ntitle: Intro\nsidebar_position: 2\n---\n# Intro\n",
    "docs/guide/_category_.yml": "label: Guides\nposition: 3\n",
    "docs/guide/install.md": "---\ntitle: Install\n---\n# Install\n",
  });
  try {
    assert.deepEqual(await navigation(root), {
      main: [
        { title: "Start", url: "/docs/start/" },
        { title: "Intro", url: "/docs/intro/" },
        { title: "Guides", children: [{ title: "Install", url: "/docs/guide/install/" }] },
      ],
    });
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test("published versions become vN folders and a navigation group", async () => {
  const root = tree({
    "versions.json": '["1.0.0"]\n',
    "versioned_docs/version-1.0.0/docs/intro.md": "---\ntitle: Intro\n---\n# Intro\n",
    "versioned_sidebars/version-1.0.0-sidebars.json": '{"docs":[{"type":"doc","id":"intro"}]}\n',
    "docs/current.md": "---\ntitle: Current\n---\n# Current\n",
  });
  try {
    const outcome = await docusaurusImporter.import(readImportSource(root));
    assert.equal(outcome.pages.find((page) => page.source.startsWith("versioned_docs/"))?.destination, "docs/v1.0.0/intro.md");
    assert.deepEqual(await navigation(root), {
      main: [{ title: "1.0.0", children: [{ title: "Intro", url: "/docs/v1.0.0/intro/" }] }],
    });
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test("translated docs keep their locale prefix and the config lists the language", async () => {
  const root = tree({
    "docusaurus.config.js":
      "module.exports = { i18n: { defaultLocale: 'en', locales: ['en', 'fa'] }, presets: [['classic', { docs: { path: 'docs' } }]] };\n",
    "docs/intro.md": "---\ntitle: Intro\n---\n# Intro\n",
    "i18n/fa/docusaurus-plugin-content-docs/current/docs/intro.md": "---\ntitle: مقدمه\n---\n# مقدمه\n",
  });
  try {
    const outcome = await docusaurusImporter.import(readImportSource(root));
    assert.equal(outcome.pages.find((page) => page.source.startsWith("i18n/"))?.destination, "fa/docs/intro.md");
    assert.match(outcome.config.contents, /languages:/);
    assert.match(outcome.config.contents, /code: "fa"/);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test("static files and images become assets the pages point at", async () => {
  const root = tree({
    "static/img/logo.png": "png",
    "docs/shot.png": "png",
    "docs/intro.md": "---\ntitle: Intro\n---\n# Intro\n\n![Logo](/img/logo.png) and ![Shot](./shot.png)\n",
  });
  try {
    const outcome = await docusaurusImporter.import(readImportSource(root));
    assert.deepEqual(outcome.assets, [
      { source: "docs/shot.png", destination: "docs/shot.png" },
      { source: "static/img/logo.png", destination: "img/logo.png" },
    ]);
    const page = outcome.pages.find((entry) => entry.source === "docs/intro.md");
    assert.match(page?.contents ?? "", /!\[Logo\]\(\/img\/logo\.png\)/);
    assert.match(page?.contents ?? "", /!\[Shot\]\(\/docs\/shot\.png\)/);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test("a multi-version site imports and builds with its version URL and asset", async () => {
  const root = tree({
    "versions.json": '["1.0.0"]\n',
    "versioned_docs/version-1.0.0/docs/intro.md": "---\ntitle: Intro\n---\n# Intro\n\n![Logo](/img/logo.png)\n",
    "static/img/logo.png": "png",
    "docs/current.md": "---\ntitle: Current\n---\n# Current\n",
  });
  const parent = mkdtempSync(join(tmpdir(), "import-docusaurus-out-"));
  const generated = join(parent, "project");
  const out = join(parent, "site");
  try {
    const source = readImportSource(root);
    const outcome = await docusaurusImporter.import(source);
    const { files } = inventoryOf(source.files, outcome.files);
    const { mappings } = buildMappings(files, outcome.pages, outcome.assets, outcome.config);
    const links = rewriteLinks(outcome.pages, mappings);
    const written = generateProject({
      source,
      destination: generated,
      mappings,
      pages: links.pages,
      assets: outcome.assets,
      config: outcome.config,
      ...(outcome.navigation === undefined ? {} : { navigation: outcome.navigation }),
    });
    assert.deepEqual(written.diagnostics.filter((diagnostic) => diagnostic.severity === "error"), []);

    const result = await build({ root: generated, out, themeRoot: THEME, defaultLayout: "doc" });
    assert.deepEqual(result.diagnostics.filter((diagnostic) => diagnostic.severity === "error"), []);
    const html = readFileSync(join(out, "docs/v1.0.0/intro/index.html"), "utf8");
    assert.match(html, /<img[^>]+src="\/img\/logo\.png"/);
  } finally {
    rmSync(root, { recursive: true, force: true });
    rmSync(parent, { recursive: true, force: true });
  }
});
