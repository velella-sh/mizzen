/**
 * Maps a Docusaurus page's front matter to this engine's keys. `title` and `description` are already the same keys and
 * stay as written; an explicit `slug` becomes `permalink` in place, so the page answers at the URL Docusaurus gave it
 * and every other line, including comments and order, stays byte for byte. Nothing is serialized or reordered.
 *
 * The URL is the page's real site-root URL: the explicit slug when it has one, else the destination's pretty URL. A
 * relative slug (`slug: setup`) is relative to the page's own folder, as Docusaurus documents it.
 */
import { parseFrontMatter } from "../../content/frontmatter.ts";
import { permalink } from "../../content/permalink.ts";

/** One page after its front matter was mapped. */
export interface MappedFrontMatter {
  /** The destination text, with `slug` rewritten to `permalink` when the page set one. */
  readonly contents: string;
  /** The site-root URL the page will answer at, trailing slash included when the source wrote one. */
  readonly url: string;
  /** Front matter `title`, for a navigation link that names this page. */
  readonly title?: string;
  /** Front matter `sidebar_label`, which wins over `title` in a sidebar. */
  readonly sidebarLabel?: string;
  /** Front matter `sidebar_position`, which orders an autogenerated sidebar. */
  readonly position?: number;
}

const FENCE = /^---[ \t]*$/;

/** A line without its terminator. */
function text(line: string): string {
  return line.replace(/\r?\n$/, "");
}

/** A URL with exactly one leading slash; `..` is resolved against the destination folder. */
function absolute(path: string): string {
  const segments: string[] = [];
  for (const segment of path.split("/")) {
    if (segment === "" || segment === ".") continue;
    if (segment === "..") segments.pop();
    else segments.push(segment);
  }
  return `/${segments.join("/")}${path.endsWith("/") && segments.length > 0 ? "/" : ""}`;
}

/** The explicit slug as a site-root URL: absolute as written, relative to the page's folder otherwise. */
function slugUrl(slug: string, destination: string): string {
  const trimmed = slug.trim();
  if (trimmed.startsWith("/")) return absolute(trimmed);
  const folder = destination.slice(0, destination.lastIndexOf("/") + 1);
  return absolute(`${folder}/${trimmed}`);
}

/** Replaces the page's `slug` line with the engine's `permalink`; other lines keep their bytes. */
function rewriteSlug(contents: string, url: string): string {
  const lines = contents.split(/(?<=\n)/);
  if (lines.length === 0 || !FENCE.test(text(lines[0]!))) return contents;
  for (let index = 1; index < lines.length; index += 1) {
    const line = lines[index]!;
    if (FENCE.test(text(line))) return contents;
    // shortcut: only a plain top-level `slug:` key is found; a quoted key or a nested one stays as it was.
    const match = /^([ \t]*)slug[ \t]*:/.exec(line);
    if (match === null) continue;
    const eol = line.endsWith("\r\n") ? "\r\n" : line.endsWith("\n") ? "\n" : "";
    lines[index] = `${match[1]}permalink: ${JSON.stringify(url)}${eol}`;
    return lines.join("");
  }
  return contents;
}

/**
 * Maps one page's front matter. `destination` is the page's path in the generated project, which decides the URL when
 * the source names no slug.
 */
export function mapFrontMatter(contents: string, destination: string): MappedFrontMatter {
  const { data } = parseFrontMatter(contents, destination);
  const title = typeof data.title === "string" ? data.title : undefined;
  const sidebarLabel = typeof data.sidebar_label === "string" ? data.sidebar_label : undefined;
  const slug = typeof data.slug === "string" && data.slug.trim() !== "" ? data.slug : undefined;
  const position = typeof data.sidebar_position === "number" ? data.sidebar_position : undefined;
  const extra = {
    ...(title === undefined ? {} : { title }),
    ...(sidebarLabel === undefined ? {} : { sidebarLabel }),
    ...(position === undefined ? {} : { position }),
  };
  if (slug === undefined) return { contents, url: permalink(destination), ...extra };
  const url = slugUrl(slug, destination);
  return { contents: rewriteSlug(contents, url), url, ...extra };
}
