/**
 * `mizzen import docusaurus` reads every docs section of a Docusaurus site. The config is scanned as text, never run:
 * a section is a `{...}` block that follows `docs:` or `@docusaurus/plugin-content-docs` and holds a `path`, so a
 * classic preset and a plugin with its own folder both become pages. Files under a section keep their paths; an
 * archived version under `versioned_docs/version-<name>/` moves into the section's `v<name>/` folder, where this
 * engine's version detection finds it; a translated page under `i18n/<locale>/…` moves under a `<locale>/` folder, the
 * URL prefix the site config declares for it. `static/` is copied at the site root, as Docusaurus serves it; a page
 * reference to a copied asset becomes the asset's site-root URL. Page front matter keeps its title, description, and
 * sidebar position, and an explicit `slug` becomes `permalink`; a manual `sidebars.js` or `sidebars.ts` becomes the
 * generated `docs` navigation, and an autogenerated list is rebuilt from the section's folders and `_category_` files.
 * The generated `mizzen.yml` says the site was imported and carries its languages.
 */
import { posix } from "node:path";
import { parse as parseYaml, stringify } from "yaml";
import type { Diagnostic, NavItem } from "../../contracts/index.ts";
import type { ImportedAsset, ImportedConfig, ImportedPage, ImportFile, ImportSource, Importer } from "../contract.ts";
import { NAVIGATION_DESTINATION } from "../mapping.ts";
import { mapFrontMatter } from "./frontmatter.ts";
import { convertSidebar, flatLinks, type CategoryMeta, type SidebarPage } from "./sidebar.ts";

/** One docs section: the folder to read and the URL prefix it is served under. */
interface DocsSection {
  readonly path: string;
  readonly routeBasePath: string;
}

/** One converted page, with what the navigation needs to link to it. */
interface SectionPage extends SidebarPage {
  readonly source: string;
}

const CONFIG = /(^|\/)docusaurus\.config\.(js|ts|mjs)$/;
const SIDEBAR = /^sidebars\.(js|ts|mjs|cjs|json)$/;
const VERSIONED_SIDEBAR = /^versioned_sidebars\/version-(.+)-sidebars\.(js|ts|mjs|cjs|json)$/;
const SECTION = /docs\s*:|@docusaurus\/plugin-content-docs/g;
const MARKDOWN = /\.mdx?$/i;
const STATIC = "static/";
const CATEGORY = /(^|\/)_category_\.(?:json|ya?ml)$/;
const VERSION_FILE = /^versions\.json$/;
const VERSIONED_DOCS = "versioned_docs/";
const I18N_DOCS = /^i18n\/([^/]+)\/docusaurus-plugin-content-docs\/(current|version-[^/]+)\/(.+)$/;

/** An error at the first line of `file`, the only position a missing-folder finding has. */
function finding(id: string, message: string, file: string): Diagnostic {
  return { id, severity: "error", message, pos: { file, line: 1, column: 1, endLine: 1, endColumn: 1 } };
}

/** A warning at the first line of `file`. */
function warning(id: string, message: string, file: string): Diagnostic {
  return { id, severity: "warning", message, pos: { file, line: 1, column: 1, endLine: 1, endColumn: 1 } };
}

/** The text of the `{...}` block that starts at or after `from`, its braces excluded. */
function blockAfter(text: string, from: number): string | undefined {
  const open = text.indexOf("{", from);
  if (open === -1) return undefined;
  let depth = 0;
  for (let i = open; i < text.length; i++) {
    if (text[i] === "{") depth++;
    else if (text[i] === "}" && --depth === 0) return text.slice(open + 1, i);
  }
  return undefined;
}

/** The quoted value of `key` in a config block. */
function quoted(block: string, key: string): string | undefined {
  return new RegExp(`\\b${key}\\s*:\\s*["']([^"']+)["']`).exec(block)?.[1];
}

/** Every docs section the config names, in the order it names them. */
function docsSections(text: string): readonly DocsSection[] {
  const sections: DocsSection[] = [];
  for (let match = SECTION.exec(text); match; match = SECTION.exec(text)) {
    const block = blockAfter(text, match.index + match[0].length);
    if (block === undefined) continue;
    const path = quoted(block, "path");
    if (path === undefined) continue;
    sections.push({ path: path.replace(/\/+$/, ""), routeBasePath: quoted(block, "routeBasePath") ?? "docs" });
  }
  return sections;
}

/** The default locale and every locale the config's `i18n` block names; Docusaurus defaults both to `en`. */
function localesOf(text: string): { readonly defaultLocale: string; readonly locales: readonly string[] } {
  const at = /\bi18n\s*:/.exec(text);
  const block = at === null ? undefined : blockAfter(text, at.index + at[0].length);
  const defaultLocale = (block === undefined ? undefined : quoted(block, "defaultLocale")) ?? "en";
  const listed = block === undefined ? undefined : /locales\s*:\s*\[([^\]]*)\]/.exec(block)?.[1];
  const locales = listed === undefined ? [] : [...listed.matchAll(/["']([^"']+)["']/g)].map((match) => match[1]!);
  return { defaultLocale, locales: locales.length === 0 ? [defaultLocale] : locales };
}

/** The generated config: the imported title, the default language, and one `languages` entry per translation. */
function generatedConfig(lang: string, languages: readonly string[]): ImportedConfig {
  const lines = ["title: Imported site", `lang: ${JSON.stringify(lang)}`];
  if (languages.length > 0) {
    lines.push("languages:");
    for (const code of languages) {
      lines.push(
        `  - code: ${JSON.stringify(code)}`,
        `    name: ${JSON.stringify(code)}`,
        `    prefix: ${JSON.stringify(`/${code}`)}`,
      );
    }
  }
  return { contents: `${lines.join("\n")}\n` };
}

/** A page's Docusaurus doc id: its path inside the section, without the extension. */
function docId(sectionPath: string, path: string): string {
  return path.slice(sectionPath.length + 1).replace(/\.mdx?$/i, "");
}

/** A version folder this engine's detection recognizes: Docusaurus's `1.0.0` becomes `v1.0.0`. */
function versionFolder(name: string): string {
  const trimmed = name.replace(/^version-/, "");
  return /^v\d/.test(trimmed) ? trimmed : `v${trimmed}`;
}

/** A URL as a duplicate check sees it: Docusaurus serves `/a` and `/a/` at the same place. */
function urlKey(url: string): string {
  return url.replace(/\/+$/, "") || "/";
}

/** The label and position a `_category_` file gives its folder. */
function categoryMeta(text: string): CategoryMeta | undefined {
  let data: unknown;
  try {
    data = parseYaml(text);
  } catch {
    return undefined;
  }
  if (typeof data !== "object" || data === null) return undefined;
  const record = data as Record<string, unknown>;
  return {
    ...(typeof record.label === "string" ? { label: record.label } : {}),
    ...(typeof record.position === "number" ? { position: record.position } : {}),
  };
}

/** An image or link target in page text, with the characters around it that must be kept. */
const TARGET = /(\]\(|src\s*=\s*["'])([^)"'\s]+)(\)|["'])/g;

/** The site-root URL a target names, when it is one of the copied assets. */
function assetUrl(target: string, page: string, assets: ReadonlyMap<string, string>): string | undefined {
  if (/^(?:[a-z][a-z\d+.-]*:|\/\/|#)/i.test(target)) return undefined;
  const path = target.startsWith("@site/")
    ? target.slice("@site/".length)
    : target.startsWith("/")
      ? `static${target}`
      : posix.normalize(posix.join(posix.dirname(page), target));
  const destination = assets.get(path);
  return destination === undefined ? undefined : `/${destination}`;
}

/** Points every page's asset references at the URL the copied asset answers at. */
function rewriteAssets(contents: string, page: string, assets: ReadonlyMap<string, string>): string {
  return contents.replace(TARGET, (match, before: string, target: string, after: string) => {
    const url = assetUrl(target, page, assets);
    return url === undefined ? match : `${before}${url}${after}`;
  });
}

export const docusaurusImporter: Importer = {
  name: "docusaurus",
  description: "a Docusaurus site",
  import(source) {
    const configPath = source.files.find((path) => CONFIG.test(path));
    if (configPath === undefined) {
      return {
        files: [],
        pages: [],
        assets: [],
        config: generatedConfig("en", []),
        diagnostics: [
          finding(
            "import.config-missing",
            "no docusaurus.config.js, docusaurus.config.ts, or docusaurus.config.mjs to read the docs sections from",
            "docusaurus.config.js",
          ),
        ],
      };
    }

    const configText = source.read(configPath);
    const locales = localesOf(configText);
    const sections = docsSections(configText);
    const files: ImportFile[] = [{ path: configPath, kind: "config" }];
    const pages: ImportedPage[] = [];
    const assets: ImportedAsset[] = [];
    const diagnostics: Diagnostic[] = [];
    const categories = new Map<string, CategoryMeta>();
    const currentPages: SectionPage[] = [];
    const localizedPages: SectionPage[] = [];
    const versionPages = new Map<string, SectionPage[]>();

    /** Converts one page and records it for the navigation and the duplicate-URL check. */
    const addPage = (from: string, to: string, section: DocsSection, rest: string, version: string | undefined, locale: string | undefined): void => {
      const mapped = mapFrontMatter(source.read(from), to);
      const id = docId(section.path, rest);
      const title = mapped.sidebarLabel ?? mapped.title ?? id.split("/").pop() ?? from;
      files.push({ path: from, kind: "content" });
      pages.push({ source: from, destination: to, contents: mapped.contents });
      const page: SectionPage = {
        source: from,
        id,
        title,
        url: mapped.url,
        ...(mapped.position === undefined ? {} : { position: mapped.position }),
      };
      if (locale !== undefined) {
        localizedPages.push(page);
        return;
      }
      if (version === undefined) currentPages.push(page);
      else {
        const list = versionPages.get(version);
        if (list === undefined) versionPages.set(version, [page]);
        else list.push(page);
      }
    };

    /** Reads a `_category_` file into the section's category map. */
    const addCategory = (path: string, folder: string): void => {
      const meta = categoryMeta(source.read(path));
      if (meta === undefined) {
        diagnostics.push(warning("import.category-invalid", `\`${path}\` is not a category mapping; its folder keeps its name and order.`, path));
      } else {
        categories.set(folder, meta);
      }
      files.push({ path, kind: "unsupported", reason: `merged into ${NAVIGATION_DESTINATION}` });
    };

    for (const section of sections) {
      const prefix = `${section.path}/`;
      const found = source.files.filter((path) => path.startsWith(prefix));
      if (found.length === 0) {
        diagnostics.push(finding("import.docs-missing", `docs section \`${section.path}\` has no files`, configPath));
        continue;
      }
      for (const path of found) {
        if (MARKDOWN.test(path)) {
          addPage(path, path, section, path, undefined, undefined);
        } else if (CATEGORY.test(path)) {
          addCategory(path, path.slice(prefix.length, path.lastIndexOf("/")));
        } else {
          files.push({ path, kind: "asset" });
          assets.push({ source: path, destination: path });
        }
      }
    }

    // shortcut: an archived page keeps its section folder inside `version-<name>/`; upgrade when a fixture versions
    // a docs plugin that Docusaurus stores under the plugin id instead.
    for (const path of source.files.filter((entry) => entry.startsWith(VERSIONED_DOCS))) {
      const match = /^versioned_docs\/version-([^/]+)\/(.+)$/.exec(path);
      const rest = match?.[2];
      const section = rest === undefined ? undefined : sections.find((entry) => rest.startsWith(`${entry.path}/`));
      if (match === null || rest === undefined || section === undefined) {
        files.push({ path, kind: "unsupported", reason: "no docs section holds this versioned file" });
        continue;
      }
      const name = match[1]!;
      const folder = versionFolder(name);
      if (MARKDOWN.test(path)) {
        const inside = rest.slice(section.path.length + 1);
        addPage(path, `${section.path}/${folder}/${inside}`, section, rest, name, undefined);
      } else {
        const inside = rest.slice(section.path.length + 1);
        const destination = `${section.path}/${folder}/${inside}`;
        files.push({ path, kind: "asset" });
        assets.push({ source: path, destination });
      }
    }

    const versionFile = source.files.find((path) => VERSION_FILE.test(path));
    if (versionFile !== undefined) {
      files.push({ path: versionFile, kind: "unsupported", reason: "versions become vN folders in the generated project" });
    }

    for (const path of source.files) {
      const match = I18N_DOCS.exec(path);
      if (match === null) continue;
      const locale = match[1]!;
      const scope = match[2]!;
      const rest = match[3]!;
      const section = sections.find((entry) => rest.startsWith(`${entry.path}/`));
      if (section === undefined) {
        files.push({ path, kind: "unsupported", reason: "no docs section holds this translated page" });
        continue;
      }
      if (!MARKDOWN.test(path)) {
        files.push({ path, kind: "unsupported", reason: "translated assets outside a docs page are not migrated" });
        continue;
      }
      const inside = rest.slice(section.path.length + 1);
      const archived = scope === "current" ? undefined : scope.slice("version-".length);
      const destination =
        archived === undefined
          ? `${locale}/${section.path}/${inside}`
          : `${locale}/${section.path}/${versionFolder(archived)}/${inside}`;
      addPage(path, destination, section, rest, undefined, locale);
    }

    const urlOwner = new Map<string, string>();
    for (const page of [...currentPages, ...localizedPages, ...[...versionPages.values()].flat()]) {
      const key = urlKey(page.url);
      const owner = urlOwner.get(key);
      if (owner === undefined) {
        urlOwner.set(key, page.source);
        continue;
      }
      diagnostics.push(
        finding("import.duplicate-url", `${page.source} and ${owner} would both be served at \`${page.url}\`; choose one of them.`, page.source),
      );
    }

    const main: NavItem[] = [];
    const sidebarPath = source.files.find((path) => SIDEBAR.test(path));
    if (sidebarPath !== undefined) {
      const sidebar = convertSidebar(source.read(sidebarPath), sidebarPath, currentPages, { categories });
      files.push({ path: sidebarPath, kind: "unsupported", reason: `merged into ${NAVIGATION_DESTINATION}` });
      diagnostics.push(...sidebar.diagnostics);
      main.push(...sidebar.items);
    }

    for (const path of source.files) {
      const match = VERSIONED_SIDEBAR.exec(path);
      if (match === null) continue;
      const name = match[1]!;
      const sidebar = convertSidebar(source.read(path), path, versionPages.get(name) ?? [], { categories });
      files.push({ path, kind: "unsupported", reason: `merged into ${NAVIGATION_DESTINATION}` });
      diagnostics.push(...sidebar.diagnostics);
      const links = flatLinks(sidebar.items);
      if (links.length > 0) main.push({ title: name, children: links });
    }

    const navigation: ImportedConfig | undefined =
      main.length === 0
        ? undefined
        : { ...(sidebarPath === undefined ? {} : { source: sidebarPath }), contents: stringify({ main }) };

    for (const path of source.files.filter((entry) => entry.startsWith(STATIC))) {
      const destination = path.slice(STATIC.length);
      if (destination === "") continue;
      files.push({ path, kind: "asset" });
      assets.push({ source: path, destination });
    }

    const bySource = new Map(assets.map((asset) => [asset.source, asset.destination]));
    const rewritten = pages.map((page) => ({ ...page, contents: rewriteAssets(page.contents, page.source, bySource) }));
    const languages = locales.locales.filter((code) => code !== locales.defaultLocale);
    return {
      files,
      pages: rewritten,
      assets,
      config: generatedConfig(locales.defaultLocale, languages),
      ...(navigation === undefined ? {} : { navigation }),
      diagnostics,
    };
  },
};
