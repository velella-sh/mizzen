/**
 * The Astro Starlight importer: reads `astro.config.*` as text, never runs it, and takes the content root from
 * `srcDir`. A page keeps its title and description, and a `draft` becomes Mizzen's `published: false`; the configured
 * `sidebar` becomes the generated `docs` navigation list. Components are converted separately.
 */
import { basename, dirname, extname, posix } from "node:path";
import { stringify } from "yaml";
import type { Diagnostic } from "../../contracts/index.ts";
import { parseFrontMatter } from "../../content/frontmatter.ts";
import { normalizeBase, permalink } from "../../content/permalink.ts";
import type { ImportedAsset, ImportedConfig, ImportedPage, ImportFile, Importer } from "../contract.ts";
import { ASSET_EXTENSIONS } from "../plain.ts";

const CONFIGS = ["astro.config.mjs", "astro.config.js", "astro.config.ts"];
const CONTENT = /\.(?:md|mdx|mdoc)$/i;
const DOCS = "content/docs";

/** A JavaScript literal the importer can read without running it. */
type JsValue = string | number | boolean | null | readonly JsValue[] | JsObject;

/** A JavaScript object literal, keyed by its property names. */
interface JsObject {
  readonly [key: string]: JsValue;
}

/** One generated navigation entry: a link when `url` is set, a group when `children` is. */
interface NavEntry {
  readonly title: string;
  readonly url?: string;
  readonly children?: readonly NavEntry[];
}

/** A converted page, as the navigation needs to see it. */
interface NavPage {
  readonly destination: string;
  readonly title: string;
  /** `sidebar.order` from the page's front matter, which sorts it in an autogenerated list. */
  readonly order?: number;
  /** `sidebar.label` from the page's front matter, which wins over the title in the navigation. */
  readonly label?: string;
}

/** One error with the first character of `file` as its position. */
function error(id: string, message: string, file?: string): Diagnostic {
  return {
    id,
    severity: "error",
    message,
    ...(file === undefined ? {} : { pos: { file, line: 1, column: 1, endLine: 1, endColumn: 1 } }),
  };
}

/** The braces' contents of `starlight({ ... })`, skipping braces inside strings, or `undefined` without the call. */
/** The contents of the `{...}` that starts at the first `{` after `from`, or `undefined`. */
function braces(text: string, from: number): string | undefined {
  const open = text.indexOf("{", from);
  if (open === -1) return undefined;
  let depth = 0;
  for (let i = open; i < text.length; i++) {
    const char = text[i]!;
    if (char === '"' || char === "'" || char === "`") {
      for (i++; i < text.length && text[i] !== char; i++) if (text[i] === "\\") i++;
    } else if (char === "{") {
      depth++;
    } else if (char === "}" && --depth === 0) {
      return text.slice(open + 1, i);
    }
  }
  return undefined;
}

/** The `starlight({...})` integration block, without its braces, or `undefined`. */
function starlightBlock(text: string): string | undefined {
  const call = /\bstarlight\s*\(/.exec(text);
  return call === null ? undefined : braces(text, call.index + call[0].length);
}

/** A quoted value of `name: "..."` in `text`, or `undefined`. */
function quoted(text: string, name: string): string | undefined {
  const match = new RegExp(`\\b${name}\\s*:\\s*(?:"([^"]*)"|'([^']*)')`).exec(text);
  return match?.[1] ?? match?.[2];
}

/** Every locale the config declares, with `root` replaced by the default locale. */
function localesOf(text: string, defaultLocale: string): readonly string[] {
  const at = /\blocales\s*:/.exec(text);
  if (at === null) return [];
  const from = at.index + at[0].length;
  const list = /^\s*\[([^\]]*)\]/.exec(text.slice(from));
  if (list !== null) return [...list[1]!.matchAll(/["']([^"']+)["']/g)].map((match) => match[1]!);
  const block = braces(text, from);
  const parsed = block === undefined ? undefined : parseLiteral(`{${block}}`);
  if (!isObject(parsed)) return [];
  return Object.keys(parsed).map((code) => (code === "root" ? defaultLocale : code));
}

/** The site base: the `base` option, else the path part of `site`. */
function baseOf(text: string): string {
  const direct = quoted(text, "base");
  if (direct !== undefined) return normalizeBase(direct);
  const site = quoted(text, "site");
  if (site === undefined) return "";
  const scheme = site.indexOf("://");
  return normalizeBase(scheme === -1 ? site : site.slice(scheme + 3).replace(/^[^/]*/, ""));
}

/** True for an object literal, never an array. */
function isObject(value: JsValue | undefined): value is JsObject {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

/**
 * Parses one JavaScript literal — string, number, boolean, `null`, array, or object — at the start of `text`, skipping
 * whitespace and comments. A template interpolation, a call, or a name other than a keyword fails the whole parse.
 */
function parseLiteral(text: string): JsValue | undefined {
  let at = 0;

  const skip = (): void => {
    for (;;) {
      const char = text[at];
      if (char === undefined) return;
      if (/\s/.test(char)) {
        at++;
      } else if (char === "/" && text[at + 1] === "/") {
        const end = text.indexOf("\n", at + 2);
        at = end === -1 ? text.length : end + 1;
      } else if (char === "/" && text[at + 1] === "*") {
        const end = text.indexOf("*/", at + 2);
        at = end === -1 ? text.length : end + 2;
      } else {
        return;
      }
    }
  };

  const string = (): string | undefined => {
    const quote = text[at];
    if (quote !== '"' && quote !== "'" && quote !== "`") return undefined;
    at++;
    let out = "";
    while (at < text.length) {
      const char = text[at]!;
      if (char === quote) {
        at++;
        return out;
      }
      if (quote === "`" && char === "$" && text[at + 1] === "{") return undefined;
      if (char === "\\") {
        const next = text[at + 1];
        at += 2;
        if (next === undefined) return undefined;
        out += next === "n" ? "\n" : next === "t" ? "\t" : next === "r" ? "\r" : next;
      } else {
        out += char;
        at++;
      }
    }
    return undefined;
  };

  const array = (): readonly JsValue[] | undefined => {
    at++;
    const out: JsValue[] = [];
    for (;;) {
      skip();
      if (text[at] === "]") {
        at++;
        return out;
      }
      if (text[at] === ",") {
        at++;
        continue;
      }
      const item = value();
      if (item === undefined) return undefined;
      out.push(item);
      skip();
      if (text[at] === ",") at++;
    }
  };

  const object = (): JsObject | undefined => {
    at++;
    const out: Record<string, JsValue> = {};
    for (;;) {
      skip();
      if (text[at] === "}") {
        at++;
        return out;
      }
      if (text[at] === ",") {
        at++;
        continue;
      }
      let key: string | undefined;
      if (text[at] === '"' || text[at] === "'" || text[at] === "`") {
        key = string();
      } else {
        key = /^[A-Za-z_$][\w$]*/.exec(text.slice(at))?.[0];
        if (key !== undefined) at += key.length;
      }
      if (key === undefined) return undefined;
      skip();
      if (text[at] !== ":") return undefined;
      at++;
      skip();
      const item = value();
      if (item === undefined) return undefined;
      out[key] = item;
      skip();
      if (text[at] === ",") at++;
    }
  };

  const value = (): JsValue | undefined => {
    skip();
    const char = text[at];
    if (char === "[" || char === "{") return char === "[" ? array() : object();
    if (char === '"' || char === "'" || char === "`") return string();
    const number = /^-?\d+(?:\.\d+)?/.exec(text.slice(at));
    if (number !== null) {
      at += number[0].length;
      return Number(number[0]);
    }
    const name = /^[A-Za-z_$][\w$]*/.exec(text.slice(at))?.[0];
    if (name === "true" || name === "false") {
      at += name.length;
      return name === "true";
    }
    if (name === "null") {
      at += name.length;
      return null;
    }
    return undefined;
  };

  return value();
}

/** The literal list of a `sidebar: [...]` in the integration block, or `undefined` when it is absent or not one. */
function sidebar(block: string): readonly JsValue[] | undefined {
  const match = /\bsidebar\s*:/.exec(block);
  if (match === null) return undefined;
  const value = parseLiteral(block.slice(match.index + match[0].length));
  return Array.isArray(value) ? value : undefined;
}

/** A page's text with its front matter mapped, and the title and sidebar settings the navigation reads. */
function convertPage(
  text: string,
  file: string,
  diagnostics: Diagnostic[],
): { contents: string; title: string; order?: number; label?: string } {
  const frontMatter = parseFrontMatter(text, file);
  diagnostics.push(...frontMatter.diagnostics);
  const mapped: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(frontMatter.data)) {
    if (key === "draft") {
      if (value === true) mapped.published = false;
      continue;
    }
    mapped[key] = value;
  }
  const sidebar = typeof mapped.sidebar === "object" && mapped.sidebar !== null && !Array.isArray(mapped.sidebar)
    ? (mapped.sidebar as Record<string, unknown>)
    : undefined;
  const title =
    typeof mapped.title === "string" && mapped.title.trim() !== ""
      ? mapped.title
      : basename(file).replace(/\.[^.]+$/, "");
  const front = Object.keys(mapped).length === 0 ? "" : `---\n${stringify(mapped)}---\n`;
  return {
    contents: front + frontMatter.body,
    title,
    ...(typeof sidebar?.order === "number" ? { order: sidebar.order } : {}),
    ...(typeof sidebar?.label === "string" ? { label: sidebar.label } : {}),
  };
}

/** The URL of a `link`: an external or site path as written, a relative path from the site root. */
function linkUrl(link: string): string {
  return /^(?:[a-z][a-z\d+.-]*:|\/\/|\/)/i.test(link) ? link : `/${link}`;
}

/** The navigation title of a page: its `sidebar.label`, else its title. */
function navTitle(page: NavPage): string {
  return page.label ?? page.title;
}

/** A folder's title: its index page's label or title, else the folder name in words. */
function folderTitle(folder: string, pages: readonly NavPage[]): string {
  const index = pages.find((page) => page.destination === `${folder}/index.md` || page.destination === `${folder}.md`);
  if (index !== undefined) return navTitle(index);
  const name = folder.slice(folder.lastIndexOf("/") + 1);
  return name.replace(/[-_]+/g, " ");
}

/** The page a `slug` names, or a page derived from it when the import has none. */
function slugEntry(slug: string, pages: readonly NavPage[]): NavEntry | undefined {
  const path = slug.replace(/^\/+|\/+$/g, "");
  if (path === "") return undefined;
  const page = pages.find((candidate) => candidate.destination.replace(/\.md$/, "") === path);
  if (page !== undefined) return { title: navTitle(page), url: permalink(page.destination) };
  return { title: basename(path), url: permalink(`${path}.md`) };
}

/**
 * The pages an `autogenerate: { directory }` covers, rebuilt from the folder tree: pages in the folder become links,
 * each subfolder becomes a group named by its index page, and both are sorted by `sidebar.order` and then title.
 */
function autogenerated(directory: string, pages: readonly NavPage[]): readonly NavEntry[] {
  const prefix = directory.replace(/^\.?\/+|\/+$/g, "");
  const base = prefix === "" ? "" : `${prefix}/`;
  const rows: { readonly order: number; readonly title: string; readonly entry: NavEntry }[] = [];
  const folders = new Map<string, NavPage[]>();
  for (const page of pages) {
    if (!page.destination.startsWith(base)) continue;
    const rest = page.destination.slice(base.length);
    const slash = rest.indexOf("/");
    if (slash === -1) {
      rows.push({ order: page.order ?? Number.POSITIVE_INFINITY, title: navTitle(page), entry: { title: navTitle(page), url: permalink(page.destination) } });
      continue;
    }
    const folder = rest.slice(0, slash);
    const list = folders.get(folder) ?? [];
    list.push(page);
    folders.set(folder, list);
  }
  for (const [folder, inside] of folders) {
    const children = autogenerated(`${base}${folder}/`, inside).flatMap((entry) => flattened(entry));
    if (children.length === 0) continue;
    const index = inside.find((page) => page.destination === `${base}${folder}/index.md`);
    rows.push({
      order: index?.order ?? Number.POSITIVE_INFINITY,
      title: folderTitle(`${base}${folder}`, inside),
      entry: { title: folderTitle(`${base}${folder}`, inside), children },
    });
  }
  rows.sort((a, b) => a.order - b.order || (a.title < b.title ? -1 : a.title > b.title ? 1 : 0));
  return rows.map((row) => row.entry);
}

/** Every link in an entry, flattening a nested group because a navigation group holds links only. */
function flattened(entry: NavEntry): readonly NavEntry[] {
  return entry.children === undefined ? [entry] : entry.children.flatMap(flattened);
}

/** One sidebar entry as a navigation item, or `undefined` when it names no page, link, or group. */
function navEntry(value: JsValue, pages: readonly NavPage[]): NavEntry | undefined {
  if (typeof value === "string") return slugEntry(value, pages);
  if (!isObject(value)) return undefined;
  const label = typeof value.label === "string" ? value.label : undefined;
  if (typeof value.link === "string") return { title: label ?? basename(value.link), url: linkUrl(value.link) };
  if (typeof value.slug === "string") {
    const entry = slugEntry(value.slug, pages);
    if (entry === undefined) return undefined;
    return label === undefined ? entry : { ...entry, title: label };
  }
  if (Array.isArray(value.items)) {
    const children = value.items.flatMap((item) => {
      const entry = navEntry(item, pages);
      return entry === undefined ? [] : flattened(entry);
    });
    return label === undefined || children.length === 0 ? undefined : { title: label, children };
  }
  if (isObject(value.autogenerate) && typeof value.autogenerate.directory === "string") {
    const children = autogenerated(value.autogenerate.directory, pages).flatMap((entry) => flattened(entry));
    return label === undefined || children.length === 0 ? undefined : { title: label, children };
  }
  return undefined;
}

/** A source path relative to the content root, with only its last separator removed. */
function relativeTo(root: string, path: string): string {
  return path.startsWith(`${root}/`) ? path.slice(root.length + 1) : path;
}

export const starlightImporter: Importer = {
  name: "starlight",
  description: "an Astro Starlight site",
  import(source) {
    const files: ImportFile[] = [];
    const pages: ImportedPage[] = [];
    const assets: ImportedAsset[] = [];
    const navPages: NavPage[] = [];
    const diagnostics: Diagnostic[] = [];

    const configPath = CONFIGS.find((name) => source.files.includes(name));
    const configText = configPath === undefined ? undefined : source.read(configPath);
    const block = configText === undefined ? undefined : starlightBlock(configText);
    if (configPath === undefined) {
      diagnostics.push(error("import.config-missing", "no astro.config.mjs, astro.config.js, or astro.config.ts"));
    } else if (block === undefined) {
      diagnostics.push(error("import.starlight-missing", "the Astro config has no starlight({...}) integration", configPath));
    }

    const title = block === undefined ? undefined : quoted(block, "title");
    const defaultLocale = quoted(block ?? "", "defaultLocale") ?? quoted(configText ?? "", "defaultLocale") ?? "en";
    const languages = (configText === undefined ? [] : localesOf(configText, defaultLocale))
      .filter((code) => code !== defaultLocale);
    const base = configText === undefined ? "" : baseOf(configText);
    const config: ImportedConfig = {
      ...(configPath === undefined ? {} : { source: configPath }),
      contents: [
        `title: ${title ?? basename(source.root)}\n`,
        ...(base === "" ? [] : [`base: ${JSON.stringify(base)}\n`]),
        ...(defaultLocale === "en" ? [] : [`lang: ${JSON.stringify(defaultLocale)}\n`]),
        ...(languages.length === 0
          ? []
          : [stringify({ languages: languages.map((code) => ({ code, name: code, prefix: `/${code}` })) })]),
      ].join(""),
    };

    const srcDir = (configText === undefined ? undefined : quoted(configText, "srcDir")) ?? "src";
    const root = `${srcDir.replace(/^\.\//, "").replace(/\/+$/, "")}/${DOCS}`;
    const under = (path: string): boolean => path.startsWith(`${root}/`);

    if (configPath !== undefined && !source.files.some(under)) {
      diagnostics.push(error("import.content-root", `no ${root} folder`, configPath));
    }

    for (const path of source.files) {
      if (path === configPath) {
        files.push({ path, kind: "config" });
        continue;
      }
      if (!under(path)) continue;
      const relative = relativeTo(root, path);
      if (CONTENT.test(relative)) {
        const destination = relative.replace(/\.(?:mdx|mdoc)$/i, ".md");
        const page = convertPage(source.read(path), path, diagnostics);
        files.push({ path, kind: "content" });
        pages.push({ source: path, destination, contents: page.contents });
        navPages.push({
          destination,
          title: page.title,
          ...(page.order === undefined ? {} : { order: page.order }),
          ...(page.label === undefined ? {} : { label: page.label }),
        });
      } else if (ASSET_EXTENSIONS.has(extname(relative).toLowerCase())) {
        files.push({ path, kind: "asset" });
        assets.push({ source: path, destination: relative });
      } else {
        files.push({ path, kind: "unsupported", reason: "not a Markdown page or a static file" });
      }
    }

    // Astro copies the public folder to the site root, whatever its files are.
    const publicDir = (quoted(configText ?? "", "publicDir") ?? "public").replace(/^\.\//, "").replace(/\/+$/, "");
    for (const path of source.files) {
      if (!path.startsWith(`${publicDir}/`)) continue;
      files.push({ path, kind: "asset" });
      assets.push({ source: path, destination: path.slice(publicDir.length + 1) });
    }

    // A relative asset a page names must exist in the source, or the built page shows a hole.
    const known = new Set(source.files);
    for (const page of pages) {
      for (const match of page.contents.matchAll(/(?:\]\(|src\s*=\s*["'])([^)"'\s]+)/g)) {
        const target = match[1]!;
        if (/^(?:[a-z][a-z\d+.-]*:|\/\/|#|\/)/i.test(target)) continue;
        const path = posix.normalize(posix.join(dirname(page.source), target.split(/[?#]/)[0]!));
        if (known.has(path) || !ASSET_EXTENSIONS.has(extname(path).toLowerCase())) continue;
        diagnostics.push({
          ...error("import.asset-missing", `\`${target}\` names no file in the source, so the page will point at nothing`, page.source),
          severity: "warning",
        });
      }
    }


    const items = block === undefined ? undefined : sidebar(block);
    const navigation: ImportedConfig | undefined =
      items === undefined
        ? undefined
        : {
            ...(configPath === undefined ? {} : { source: configPath }),
            contents: stringify({
              main: items.flatMap((item) => {
                const entry = navEntry(item, navPages);
                return entry === undefined ? [] : [entry];
              }),
            }),
          };

    return {
      files,
      pages,
      assets,
      config,
      ...(base === "" ? {} : { base }),
      ...(root === "" ? {} : { contentRoot: `${root}/` }),
      ...(navigation === undefined ? {} : { navigation }),
      diagnostics,
    };
  },
};
